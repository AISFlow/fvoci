/**
 * Writes `src/lib/editor/katex.css` from the style sheet of the installed
 * formula library (KaTeX).
 *
 *   node tools/math/katex-css.ts            write the file
 *   node tools/math/katex-css.ts --check    fail when it is not what would be written
 *
 * The library's own sheet offers every font in three formats (WOFF2, WOFF,
 * TrueType), and a bundler that follows it ships all sixty files. Every
 * browser this app runs in reads WOFF2, so the copy written here names only
 * those twenty, by their path inside the package. Nothing else is changed.
 * A browser fetches a font file only when a formula uses a character of it.
 *
 * The output is committed: the app imports it, and a test fails when it no
 * longer matches the installed package (after an upgrade, run this again).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import { format, resolveConfig } from 'prettier';

import { packageDirectory } from '../licenses/packages.ts';

const WEB_ROOT = path.resolve(import.meta.dirname, '../..');
export const KATEX_CSS_FILE = 'src/lib/editor/katex.css';

/** One source of a font face as the library writes it. */
const SOURCES =
  /src:\s*url\(fonts\/([\w-]+)\.woff2\)\s*format\("woff2"\),\s*url\(fonts\/\1\.woff\)\s*format\("woff"\),\s*url\(fonts\/\1\.ttf\)\s*format\("truetype"\);/g;

export interface KatexCss {
  css: string;
  /** The font files the sheet names, without extension. */
  fonts: string[];
  version: string;
}

/** The library's sheet with every font face reduced to its WOFF2 file. */
export async function katexCss(): Promise<KatexCss> {
  const directory = packageDirectory('katex');
  const { version } = JSON.parse(readFileSync(path.join(directory, 'package.json'), 'utf8')) as {
    version: string;
  };
  const original = readFileSync(path.join(directory, 'dist/katex.css'), 'utf8');
  const fonts: string[] = [];
  const reduced = original.replace(SOURCES, (_match, name: string) => {
    fonts.push(name);
    return `src: url('katex/dist/fonts/${name}.woff2') format('woff2');`;
  });
  const faces = original.match(/@font-face/g)?.length ?? 0;
  if (fonts.length === 0 || fonts.length !== faces || /\.(woff|ttf)\b(?!2)/.test(reduced)) {
    throw new Error(
      `katex ${version}: the font faces of dist/katex.css are not written the way this tool expects (${fonts.length} of ${faces} rewritten)`,
    );
  }
  const header =
    `/*\n * Generated by tools/math/katex-css.ts from katex ${version} (dist/katex.css, MIT licence;\n` +
    ` * the fonts are under the SIL Open Font License 1.1). Do not edit: run the tool.\n` +
    ` * The only change is that each font face names its WOFF2 file alone.\n */\n`;
  const file = path.join(WEB_ROOT, KATEX_CSS_FILE);
  const css = await format(header + reduced, { ...(await resolveConfig(file)), parser: 'css' });
  return { css, fonts, version };
}

if (import.meta.main) {
  const mode = process.argv[2];
  const { css, fonts, version } = await katexCss();
  const file = path.join(WEB_ROOT, KATEX_CSS_FILE);
  if (mode === '--check') {
    let current = '';
    try {
      current = readFileSync(file, 'utf8');
    } catch {
      // Missing counts as stale.
    }
    if (current !== css) {
      console.error(`${KATEX_CSS_FILE} is stale: run "node tools/math/katex-css.ts"`);
      process.exit(1);
    }
    console.log(`${KATEX_CSS_FILE}: up to date (katex ${version}, ${fonts.length} fonts)`);
  } else {
    writeFileSync(file, css);
    console.log(`${KATEX_CSS_FILE}: written (katex ${version}, ${fonts.length} fonts, WOFF2 only)`);
  }
}
